"""Freeze Unicode Nd digit blocks from the historical Python 3.12.10 oracle.

Run with that interpreter; the output is independent of host Rust Unicode tables.
"""

import sys
import unicodedata
from pathlib import Path

if sys.version_info[:3] != (3, 12, 10) or unicodedata.unidata_version != "15.0.0":
    raise SystemExit("Generation requires Python 3.12.10 / Unicode 15.0.0")

starts = [n for n in range(sys.maxunicode + 1) if unicodedata.decimal(chr(n), None) == 0]
for start in starts:
    assert [unicodedata.decimal(chr(start + n)) for n in range(10)] == list(range(10))
rows = "\n".join(
    "    " + ", ".join(f"0x{x:X}" for x in starts[i : i + 8]) + ","
    for i in range(0, len(starts), 8)
)
output = """//! Frozen Unicode 15.0.0 Nd blocks, generated by scripts/generate-decimal-digits.py.
//! Historical oracle: CPython 3.12.10. Never use host Unicode versions for admission.
const ZERO_CODEPOINTS: &[u32] = &[
ROWS
];

pub(super) fn normalize(text: &str) -> String {
    text.chars().map(|ch| {
        let codepoint = ch as u32;
        let index = ZERO_CODEPOINTS.partition_point(|start| *start <= codepoint);
        let digit = index.checked_sub(1).map(|index| codepoint - ZERO_CODEPOINTS[index]);
        match digit {
            Some(digit) if digit < 10 => (b'0' + digit as u8) as char,
            _ => ch,
        }
    }).collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn all_frozen_digits_and_non_decimal_categories() {
        for start in ZERO_CODEPOINTS {
            let text: String = (0..10).map(|offset| char::from_u32(start + offset).unwrap()).collect();
            assert_eq!(normalize(&text), "0123456789");
        }
        // Superscripts/fractions are numeric, but not decimal digits. Unicode
        // 16's Garay digits are intentionally absent from the historical table.
        assert_eq!(normalize("²½\\u{10D40}"), "²½\\u{10D40}");
    }
}
""".replace("ROWS", rows)
(Path(__file__).resolve().parents[1] / "packages/xian-vm-core/src/decimal_digits.rs").write_text(
    output
)
