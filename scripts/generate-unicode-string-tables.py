#!/usr/bin/env python3
"""Pin string properties to the historical Python 3.12 / Unicode 15 runtime.

Run with the historical interpreter, not the development interpreter. Regenerate
only as part of an explicitly reviewed consensus Unicode-version change.
"""

import argparse
import ctypes
import hashlib
import sys
import unicodedata
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / "packages/xian-vm-core/src/unicode_string_tables.rs"


def unicode_property(name):
    function = getattr(ctypes.pythonapi, name)
    function.argtypes = [ctypes.c_uint32]
    function.restype = ctypes.c_int
    return function


def properties(char, is_cased, is_ignorable):
    return (
        int(char.isalpha())
        | (int(char.isdigit()) << 1)
        | (int(char.isnumeric()) << 2)
        | (int(char.islower()) << 3)
        | (int(is_cased(ord(char))) << 4)
        | (int(char.isspace()) << 5)
        | (int(is_ignorable(ord(char))) << 6)
    )


def generate():
    if sys.version_info[:2] != (3, 12) or unicodedata.unidata_version != "15.0.0":
        raise SystemExit("Generation requires Python 3.12 with Unicode 15.0.0")
    is_cased = unicode_property("_PyUnicode_IsCased")
    is_ignorable = unicode_property("_PyUnicode_IsCaseIgnorable")
    values = bytes(properties(chr(code), is_cased, is_ignorable) for code in range(0x110000))
    rows = []
    start = 0
    for end in range(1, len(values) + 1):
        if end == len(values) or values[start] != values[end]:
            if values[start]:
                rows.append(f"    (0x{start:04X}, 0x{end - 1:04X}, {values[start]}),")
            start = end
    digest = hashlib.sha256(values).hexdigest()
    return (
        "// Generated by scripts/generate-unicode-string-tables.py.\n"
        "// Source: Python 3.12, Unicode 15.0.0. Do not edit by hand.\n"
        "// Flags: alpha=1, digit=2, numeric=4, lower=8, cased=16, space=32, case_ignorable=64.\n"
        "#[cfg(test)]\npub(super) const PROPERTIES_SHA256: &str =\n"
        f'    "{digest}";\n'
        "pub(super) const RANGES: &[(u32, u32, u8)] = &[\n"
        + "\n".join(rows)
        + "\n];\n"
        + case_mapping("lower")
        + case_mapping("upper")
    )


def case_mapping(method):
    rows = []
    digest = hashlib.sha256()
    for code in range(0x110000):
        if 0xD800 <= code <= 0xDFFF:
            continue
        char = chr(code)
        mapped = getattr(char, method)()
        encoded = mapped.encode("utf-8")
        digest.update(code.to_bytes(4, "big"))
        digest.update(len(encoded).to_bytes(4, "big"))
        digest.update(encoded)
        if mapped != char:
            escaped = "".join("\\u{" + f"{ord(part):X}" + "}" for part in mapped)
            rows.append(f'    (0x{code:04X}, "{escaped}"),')
    name = method.upper()
    return (
        f"#[cfg(test)]\npub(super) const {name}_SHA256: &str =\n"
        f'    "{digest.hexdigest()}";\n'
        f"pub(super) const {name}: &[(u32, &str)] = &[\n" + "\n".join(rows) + "\n];\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if OUTPUT.read_text() != content:
            raise SystemExit("Unicode string tables are stale")
    else:
        OUTPUT.write_text(content)


if __name__ == "__main__":
    main()
